import 'names.dart';

const _llTypeEn = {
  'metropolitan': 'Metropolitan City',
  'subMetropolitan': 'Sub-Metropolitan City',
  'municipality': 'Municipality',
  'ruralMunicipality': 'Rural Municipality',
};

const _paTypeEn = {
  'nationalPark': 'National Park',
  'wildlifeReserve': 'Wildlife Reserve',
  'huntingReserve': 'Hunting Reserve',
  'watershedAndWildlifeReserve': 'Watershed and Wildlife Reserve',
  'developmentArea': 'Development Area',
};

/// Valid `type` values per level, used by validation.
final validTypes = {
  'province': {''},
  'district': {''},
  'local_level': _llTypeEn.keys.toSet(),
  'protected_area': _paTypeEn.keys.toSet(),
};

const _reserved = {
  'abstract', 'as', 'assert', 'async', 'await', 'base', 'break', 'case',
  'catch', 'class', 'const', 'continue', 'covariant', 'default', 'deferred',
  'do', 'dynamic', 'else', 'enum', 'export', 'extends', 'extension',
  'external', 'factory', 'false', 'final', 'finally', 'for', 'function',
  'get', 'hide', 'if', 'implements', 'import', 'in', 'interface', 'is',
  'late', 'library', 'mixin', 'new', 'null', 'of', 'on', 'operator', 'part',
  'required', 'rethrow', 'return', 'sealed', 'set', 'show', 'static', 'super',
  'switch', 'sync', 'this', 'throw', 'true', 'try', 'type', 'typedef', 'var',
  'void', 'when', 'while', 'with', 'yield',
  // Members every enum already has.
  'values', 'index', 'name', 'hashCode', 'runtimeType', 'toString',
};

/// `'Nawalparasi East'` → `'nawalparasiEast'`.
String camelCase(String s) {
  final words = s
      .split(RegExp('[^A-Za-z0-9]+'))
      .where((w) => w.isNotEmpty)
      .map((w) => w.toLowerCase())
      .toList();
  final id =
      words.first +
      words.skip(1).map((w) => w[0].toUpperCase() + w.substring(1)).join();
  return RegExp('^[0-9]').hasMatch(id) ? 'n$id' : id;
}

String _lit(String s) =>
    "'${s.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$')}'";

/// Enum identifiers keyed by code. Local levels that share a name get the
/// district appended (`kalikaChitwan`); throws if that still collides.
Map<String, String> identifiers(List<NameRow> rows) {
  final byCode = {for (final r in rows) r.code: r};
  final ids = <String, String>{};
  for (final level in levels) {
    final group = rows.where((r) => r.level == level).toList();
    final counts = <String, int>{};
    for (final r in group) {
      final base = camelCase(r.nameEn);
      counts[base] = (counts[base] ?? 0) + 1;
    }
    final seen = <String>{};
    for (final r in group) {
      var id = camelCase(r.nameEn);
      if (counts[id]! > 1 || _reserved.contains(id)) {
        final parent = byCode[r.parentCode];
        if (parent == null) {
          throw StateError('Cannot disambiguate "${r.nameEn}" (${r.code})');
        }
        final suffix = camelCase(parent.nameEn);
        id += suffix[0].toUpperCase() + suffix.substring(1);
      }
      if (!seen.add(id)) {
        throw StateError('Duplicate identifier "$id" for ${r.code}');
      }
      ids[r.code] = id;
    }
  }
  return ids;
}

/// Generates `lib/src/data/models/region.g.dart`.
///
/// Missing Nepali names fall back to English so the code always compiles;
/// `--strict` builds refuse to get this far.
String generateRegions(
  List<NameRow> rows,
  Map<String, List<String>> protectedAreaDistricts,
) {
  final ids = identifiers(rows);
  final byCode = {for (final r in rows) r.code: r};
  String ne(NameRow r) => r.nameNe.isEmpty ? r.nameEn : r.nameNe;
  String name(NameRow r) => 'LocalizedName(${_lit(r.nameEn)}, ${_lit(ne(r))})';
  String pending(NameRow r) => r.nameNe.isEmpty ? ' Nepali name pending.' : '';
  Iterable<NameRow> of(String level) => rows.where((r) => r.level == level);

  final b = StringBuffer()
    ..writeln(
      '// GENERATED by tool/build_data.dart from tool/source/names.csv.',
    )
    ..writeln('// Do not edit by hand: change names.csv and re-run the build.')
    ..writeln(
      '// Boundary data: OKNP LocalBoundaries, CC BY 4.0 '
      '(see DATA_LICENSE.md).',
    )
    ..writeln()
    ..writeln("part of 'region.dart';")
    ..writeln()
    ..writeln("/// Nepal's 7 provinces.")
    ..writeln('enum Province with _ProvinceMembers implements Region {');
  for (final r in of('province')) {
    b
      ..writeln('  /// ${r.nameEn} Province.${pending(r)}')
      ..writeln(
        "  ${ids[r.code]}('${r.code}', ${r.code.substring(1)}, "
        '${name(r)}),',
      );
  }
  b
    ..writeln('  ;')
    ..writeln()
    ..writeln('  const Province(this.code, this.number, this.name);')
    ..writeln()
    ..writeln('  @override')
    ..writeln('  final String code;')
    ..writeln()
    ..writeln('  /// Official province number, 1–7 (east to west).')
    ..writeln('  final int number;')
    ..writeln()
    ..writeln('  @override')
    ..writeln('  final LocalizedName name;')
    ..writeln()
    ..writeln('  @override')
    ..writeln('  AdminLevel get level => AdminLevel.province;')
    ..writeln('}')
    ..writeln()
    ..writeln("/// Nepal's 77 districts.")
    ..writeln('enum District with _DistrictMembers implements Region {');
  for (final r in of('district')) {
    final p = byCode[r.parentCode]!;
    b
      ..writeln(
        '  /// ${r.nameEn} District, ${p.nameEn} Province.'
        '${pending(r)}',
      )
      ..writeln(
        "  ${ids[r.code]}('${r.code}', ${name(r)}, "
        'Province.${ids[p.code]}),',
      );
  }
  b
    ..writeln('  ;')
    ..writeln()
    ..writeln('  const District(this.code, this.name, this.province);')
    ..writeln()
    ..writeln('  @override')
    ..writeln('  final String code;')
    ..writeln()
    ..writeln('  @override')
    ..writeln('  final LocalizedName name;')
    ..writeln()
    ..writeln('  @override')
    ..writeln('  final Province province;')
    ..writeln()
    ..writeln('  @override')
    ..writeln('  AdminLevel get level => AdminLevel.district;')
    ..writeln('}')
    ..writeln()
    ..writeln("/// Nepal's 753 local levels (gaunpalika and nagarpalika).")
    ..writeln('enum LocalLevel with _LocalLevelMembers implements Region {');
  for (final r in of('local_level')) {
    final d = byCode[r.parentCode]!;
    b
      ..writeln(
        '  /// ${r.nameEn} ${_llTypeEn[r.type]}, ${d.nameEn} District.'
        '${pending(r)}',
      )
      ..writeln(
        "  ${ids[r.code]}('${r.code}', ${name(r)}, "
        'District.${ids[d.code]}, LocalLevelType.${r.type}),',
      );
  }
  b
    ..writeln('  ;')
    ..writeln()
    ..writeln(
      '  const LocalLevel(this.code, this.name, this.district, '
      'this.type);',
    )
    ..writeln()
    ..writeln('  @override')
    ..writeln('  final String code;')
    ..writeln()
    ..writeln('  @override')
    ..writeln('  final LocalizedName name;')
    ..writeln()
    ..writeln('  /// The district this local level belongs to.')
    ..writeln('  final District district;')
    ..writeln()
    ..writeln('  /// Metropolitan city, municipality, etc.')
    ..writeln('  final LocalLevelType type;')
    ..writeln()
    ..writeln('  @override')
    ..writeln('  AdminLevel get level => AdminLevel.localLevel;')
    ..writeln('}')
    ..writeln()
    ..writeln('/// Protected areas that lie outside every local level.')
    ..writeln('///')
    ..writeln(
      '/// This is not a complete list of protected areas in Nepal: '
      'parks such as',
    )
    ..writeln('/// Sagarmatha lie inside local levels and are not listed here.')
    ..writeln('enum ProtectedArea with _ProtectedAreaMembers {');
  for (final r in of('protected_area')) {
    final districts = protectedAreaDistricts[r.code]!
        .map((c) => 'District.${ids[c]}')
        .join(', ');
    b
      ..writeln('  /// ${r.nameEn} ${_paTypeEn[r.type]}.${pending(r)}')
      ..writeln(
        "  ${ids[r.code]}('${r.code}', ${name(r)}, "
        'ProtectedAreaType.${r.type}, [$districts]),',
      );
  }
  b
    ..writeln('  ;')
    ..writeln()
    ..writeln(
      '  const ProtectedArea(this.code, this.name, this.type, '
      'this.districts);',
    )
    ..writeln()
    ..writeln('  /// Stable code, e.g. `PA01`.')
    ..writeln('  final String code;')
    ..writeln()
    ..writeln('  /// Name without the type, e.g. "Chitwan".')
    ..writeln('  final LocalizedName name;')
    ..writeln()
    ..writeln('  /// National park, wildlife reserve, etc.')
    ..writeln('  final ProtectedAreaType type;')
    ..writeln()
    ..writeln('  /// Districts the area extends into.')
    ..writeln('  final List<District> districts;')
    ..writeln('}')
    ..writeln()
    ..writeln('/// Alternative spellings, keyed by code. Used by search.')
    ..writeln('const Map<String, List<String>> regionAliases = {');
  for (final r in rows.where((r) => r.aliases.isNotEmpty)) {
    b.writeln("  '${r.code}': [${r.aliases.map(_lit).join(', ')}],");
  }
  b.writeln('};');
  return b.toString();
}
